// Offline import of the public-domain Mutopia MIDI editions in music-sources/.
// Run `node scripts/import-music.mjs` after editing the arrangement manifest.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';

export function readMidi(data) {
  if (data.toString('ascii', 0, 4) !== 'MThd') throw new Error('Missing MIDI header');
  const division = data.readUInt16BE(12);
  if (division & 0x8000) throw new Error('SMPTE timing is unsupported');
  const tracks = [];
  let offset = 8 + data.readUInt32BE(4);
  while (offset < data.length) {
    if (data.toString('ascii', offset, offset + 4) !== 'MTrk') throw new Error('Missing MIDI track');
    const end = offset + 8 + data.readUInt32BE(offset + 4);
    offset += 8;
    let tick = 0, running = 0;
    const track = { name: '', notes: [], meta: [] }, active = new Map();
    const variable = () => {
      let value = 0, byte;
      do { byte = data[offset++]; value = value * 128 + (byte & 127); } while (byte & 128);
      return value;
    };
    while (offset < end) {
      tick += variable();
      let status = data[offset];
      if (status & 128) offset++;
      else status = running;
      if (status === 0xff) {
        const type = data[offset++], length = variable();
        const bytes = data.subarray(offset, offset + length);
        if (type === 3) track.name = bytes.toString();
        if (type === 0x51 || type === 0x58) track.meta.push({ beat: tick / division, type, bytes: [...bytes] });
        offset += length;
      } else if (status === 0xf0 || status === 0xf7) {
        const length = variable(); offset += length; running = 0;
      } else {
        if (status < 0x80 || status >= 0xf0) throw new Error('Unsupported MIDI event');
        running = status;
        const type = status >> 4, channel = status & 15, pitch = data[offset++];
        const velocity = type === 0xc || type === 0xd ? 0 : data[offset++];
        const key = `${channel}:${pitch}`;
        if (type === 9 && velocity) {
          const queue = active.get(key) || [];
          queue.push(tick / division); active.set(key, queue);
        } else if (type === 8 || type === 9) {
          const queue = active.get(key);
          // LilyPond can emit redundant note-offs when tied voices share a pitch.
          if (queue?.length) track.notes.push({ midi: pitch, start: queue.shift(), end: tick / division, channel });
        }
      }
    }
    if ([...active.values()].some(queue => queue.length)) throw new Error('Unterminated MIDI note');
    track.notes.sort((a, b) => a.start - b.start || a.midi - b.midi);
    tracks.push(track);
  }
  return tracks;
}

export function arrange(tracks, config) {
  const notes = [];
  const { from, to } = config.excerpt;
  for (const voice of config.voices) {
    for (const note of tracks[voice.track].notes) {
      if (note.start >= to || note.end <= from) continue;
      let midi = note.midi + voice.transpose;
      // Preserve pitch class when the original register exceeds two octaves.
      while (midi < 48) midi += 12;
      while (midi > 73) midi -= 12;
      const start = Math.max(from, note.start) - from;
      const duration = Math.min(to, note.end) - Math.max(from, note.start);
      const end = start + duration - Math.min(.12, duration * .15);
      notes.push({ key: midi - 48, start, end: Number(end.toFixed(6)), power: voice.power });
    }
  }
  notes.sort((a, b) => a.start - b.start || a.key - b.key);
  return {
    id: config.id, title: config.title, composer: config.composer,
    description: config.description, bpm: config.bpm,
    beats: to - from, beatsPerBar: config.beatsPerBar, pickupBeats: config.pickupBeats || 0,
    source: config.source, notes,
  };
}

export async function generateCatalog() {
  const root = new URL('../music-sources/', import.meta.url);
  const manifest = JSON.parse(await readFile(new URL('catalog.json', root), 'utf8'));
  const songs = [];
  for (const config of manifest) {
    const midi = await readFile(new URL(config.midi, root));
    if (createHash('sha256').update(midi).digest('hex') !== config.sha256) throw new Error(`Source checksum changed: ${config.id}`);
    songs.push(arrange(readMidi(midi), config));
  }
  return '// Generated by scripts/import-music.mjs from credited public-domain scores.\n'
    + 'export const IMPORTED_SONGS = ' + JSON.stringify(songs, null, 0) + ';\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeFile(new URL('../web/music/catalog.js', import.meta.url), await generateCatalog());
  console.log('Imported nine classical arrangements.');
}
